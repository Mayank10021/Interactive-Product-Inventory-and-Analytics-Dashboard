// Packs the console scripts into js/snippets.js so the web page can show and run
// the exact same code. Re-run after editing any file in /console:  node build.js

const fs = require("fs");
const path = require("path");

const files = {
  a1: "console/assignment-1-variables.js",
  a2: "console/assignment-2-operators.js",
  a3: "console/assignment-3-conditionals.js",
  a4: "console/assignment-4-loops.js",
  a5: "console/assignment-5-functions.js",
  a6: "console/assignment-6-arrays-objects.js",
  core: "js/inventory-core.js",
};

const out = {};
Object.keys(files).forEach(function (key) {
  out[key] = fs.readFileSync(path.join(__dirname, files[key]), "utf8").replace(/\r\n/g, "\n").trimEnd() + "\n";
});

fs.writeFileSync(
  path.join(__dirname, "js", "snippets.js"),
  "// Generated by build.js. Do not edit by hand.\nwindow.SNIPPETS = " + JSON.stringify(out, null, 2) + ";\n"
);
console.log("snippets.js written with " + Object.keys(out).length + " files");
